//  What gets recorded and how long it's kept. The filters catch what apps mark as secret or
//  temporary (nspasteboard.org), password managers, excluded apps and one-time codes; they can't
//  recognise every secret.
//

import Foundation

enum ClipboardPolicy {
    static let ownMarkerType = "io.github.ibrahim-alohali.underbrim.clipboard-copy"

    /// nspasteboard.org markers for secret, temporary or generated content, and password managers' own.
    static let skippedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType", "Pasteboard generator type",
        "com.typeit4me.clipping", ownMarkerType,
    ]

    static let defaultExcludedApps: Set<String> = [
        "com.1password.1password", "com.agilebits.onepassword7", "com.bitwarden.desktop", "org.keepassxc.keepassxc",
        "com.apple.Passwords", "com.apple.keychainaccess", "com.lastpass.LastPass", "in.sinew.Enpass-Desktop",
        "com.markmcguill.strongbox.mac", "me.proton.pass.electron", "com.dashlane.dashlanephonefinal",
    ]
    /// Names for the list above when the app isn't on this Mac to ask.
    static let knownNames: [String: String] = [
        "com.1password.1password": "1Password", "com.agilebits.onepassword7": "1Password 7",
        "com.bitwarden.desktop": "Bitwarden", "org.keepassxc.keepassxc": "KeePassXC", "com.apple.Passwords": "Passwords",
        "com.apple.keychainaccess": "Keychain Access", "com.lastpass.LastPass": "LastPass", "in.sinew.Enpass-Desktop": "Enpass",
        "com.markmcguill.strongbox.mac": "Strongbox", "me.proton.pass.electron": "Proton Pass",
        "com.dashlane.dashlanephonefinal": "Dashlane",
    ]

    static let maxTextBytes = 512 * 1024
    static let maxImageBytes = 20 * 1024 * 1024
    /// Any screenshot or photo (an 8K screen is 33 megapixels). A small file
    /// can claim far more and take gigabytes to decode.
    static let maxImagePixels = 100_000_000.0

    enum SkipReason: Equatable {
        case markedSecret, excludedApp, ownCopy, oneTimeCode, tooLarge, blank
    }

    static func skipReason(types: [String], sourceBundleID: String?, excludedApps: Set<String>) -> SkipReason? {
        if types.contains(ownMarkerType) { return .ownCopy }
        if !skippedTypes.isDisjoint(with: types) { return .markedSecret }
        if let source = sourceBundleID, excludedApps.contains(source) { return .excludedApp }
        return nil
    }

    /// One-time codes come in short messages: longer copies aren't checked, so a number near a
    /// keyword can't drop a whole log, and the check costs the same whatever the size.
    static let oneTimeCodeMessageLength = 500

    static func skipReason(forText text: String) -> SkipReason? {
        if text.utf8.count > maxTextBytes { return .tooLarge }
        if isBlank(text) { return .blank }
        if text.utf16.count <= oneTimeCodeMessageLength, OTPDetector.detect(in: text) != nil { return .oneTimeCode }
        return nil
    }

    /// Shows nothing: spaces, tabs, line breaks and invisible marks (zero-width spaces, direction marks).
    /// An emoji's joiners and variation selectors are marks too, but never alone.
    static func isInvisible(_ character: Character) -> Bool {
        character.unicodeScalars.allSatisfy {
            $0.properties.isWhitespace || [.format, .control].contains($0.properties.generalCategory)
        }
    }

    /// Nothing to see, so a card of it would look empty. Stops at the first visible character.
    static func isBlank(_ text: some StringProtocol) -> Bool { text.allSatisfy(isInvisible) }

    /// What a card shows: from the first visible character (leading blank lines would fill its few lines).
    static func visibleStart(of text: String) -> Substring { text.drop(while: isInvisible) }

    static func link(in text: String) -> URL? {
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.contains(where: \.isWhitespace), trimmed.count <= 2048,
              let url = URL(string: trimmed), let scheme = url.scheme?.lowercased(),
              ["http", "https", "mailto"].contains(scheme) else { return nil }
        return url
    }

    struct Limits: Equatable {
        var maxUnpinned = 100
        var maxAge: TimeInterval = 7 * 24 * 3600
        var budgetBytes = 100_000_000  // "100 MB" as Settings shows it (decimal, like Finder)
    }

    struct PruneResult: Equatable {
        var kept: [ClipboardEntry]
        var removed: [ClipboardEntry]
        /// Pinned entries alone exceed the budget: new captures pause; pins are never dropped.
        var pinnedOverBudget: Bool
    }

    /// Unpinned entries leave by age, then by count, then oldest first until the total fits.
    static func prune(_ entries: [ClipboardEntry], now: Date, limits: Limits) -> PruneResult {
        let sorted = entries.sorted { $0.copiedAt > $1.copiedAt }
        var kept: [ClipboardEntry] = []
        var removed: [ClipboardEntry] = []
        var unpinnedCount = 0
        for entry in sorted {
            if entry.pinned { kept.append(entry); continue }
            // Kept before blank copies were skipped; nothing in them to see or paste back.
            if case .text(let text) = entry.content, isBlank(text) { removed.append(entry); continue }
            if now.timeIntervalSince(entry.copiedAt) > limits.maxAge || unpinnedCount >= limits.maxUnpinned {
                removed.append(entry)
            } else {
                unpinnedCount += 1
                kept.append(entry)
            }
        }
        var total = kept.reduce(0) { $0 + $1.byteCount }
        while total > limits.budgetBytes, let index = kept.lastIndex(where: { !$0.pinned }) {
            total -= kept[index].byteCount
            removed.append(kept.remove(at: index))
        }
        return PruneResult(kept: kept, removed: removed, pinnedOverBudget: total > limits.budgetBytes)
    }

    static func matches(_ entry: ClipboardEntry, query: String, appName: String?) -> Bool {
        let needle = query.trimmingCharacters(in: .whitespaces)
        guard !needle.isEmpty else { return true }
        let haystacks = [entry.text, appName, entry.kind == .image ? String(localized: "Image") : nil].compactMap { $0 }
        return haystacks.contains { $0.range(of: needle, options: [.caseInsensitive, .diacriticInsensitive]) != nil }
    }
}
